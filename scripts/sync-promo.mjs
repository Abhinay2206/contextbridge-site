// Converts the promo videos from the media folder into small web copies in public/,
// names them by content hash (so browsers can never serve a stale video), and writes lib/promo.ts.
// Usage: npm run promo            (reads PROMO_SRC_DIR, default below)
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = process.env.PROMO_SRC_DIR || "/Users/abhinay/Abhi/Media/motion_videos/ContextBridge-Promo";
const OUT = new URL("../public/", import.meta.url).pathname;
const FORMATS = { h: { file: "ContextBridge-Promo-16x9.mp4", scale: "1920:1080", crf: 25 }, v: { file: "ContextBridge-Promo-9x16.mp4", scale: "720:1280", crf: 25 } };
const hashOf = (p) => createHash("sha1").update(readFileSync(p)).digest("hex").slice(0, 8);
const run = (cmd, args) => execFileSync(cmd, args, { stdio: ["ignore", "ignore", "inherit"] });

const manifest = {};
for (const [k, f] of Object.entries(FORMATS)) {
  const src = join(SRC, f.file);
  if (!existsSync(src)) { console.error(`missing ${src}`); process.exit(1); }
  const h = hashOf(src), name = k === "h" ? "16x9" : "9x16";
  const video = `promo-${name}.${h}.mp4`, poster = `promo-poster-${name}.${h}.jpg`;
  if (!existsSync(OUT + video)) {
    run("ffmpeg", ["-y", "-loglevel", "error", "-i", src, "-vf", `scale=${f.scale}:flags=lanczos,fps=30`, "-c:v", "libx264", "-preset", "slow", "-crf", String(f.crf), "-profile:v", "high", "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-c:a", "aac", "-b:a", "112k", OUT + video]);
    run("ffmpeg", ["-y", "-loglevel", "error", "-ss", "10", "-i", src, "-frames:v", "1", "-vf", `scale=${f.scale.split(":")[0]}:-1`, "-q:v", "3", OUT + poster]);
  }
  const dur = Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", OUT + video]).toString());
  manifest[k] = { video: `/${video}`, poster: `/${poster}`, duration: Math.round(dur) };
  console.log(`${f.file} -> ${video} (${Math.round(dur)} s)`);
}
// remove superseded promo files
const keep = new Set(Object.values(manifest).flatMap((m) => [m.video.slice(1), m.poster.slice(1)]));
for (const f of readdirSync(OUT)) if (/^promo-.*\.(mp4|jpg)$/.test(f) && !keep.has(f)) { rmSync(OUT + f); console.log("removed old", f); }
writeFileSync(new URL("../lib/promo.ts", import.meta.url), `// Generated by scripts/sync-promo.mjs. Do not edit.\nexport const PROMO = ${JSON.stringify(manifest, null, 2)} as const;\n`);
